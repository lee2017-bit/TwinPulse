"""Generate/check the browser copy of the versioned engine contract.

The Python contract remains authoritative.  R5 consumes this generated file
instead of maintaining a second handwritten list of engine commands/states.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "packages" / "twinpulse_core" / "src"))

from twinpulse_core.engine_contracts import (  # noqa: E402
    COMMAND_STATUSES,
    COMMAND_TYPES,
    ENGINE_SCHEMA_VERSION,
    RUNTIME_STATES,
)


TARGET = ROOT / "apps" / "twinpulse-web" / "src" / "engine-contracts.ts"


def _array(name: str, values: set[str] | frozenset[str]) -> str:
    members = ", ".join(f'"{value}"' for value in sorted(values))
    return f"export const {name} = [{members}] as const;"


def render() -> str:
    return f'''// GENERATED by scripts/generate_engine_ts.py. Do not edit by hand.
// SPDX-FileCopyrightText: 2026 Jaewon Lee
// SPDX-License-Identifier: Apache-2.0
// Source: https://github.com/lee2017-bit/TwinPulse
export const ENGINE_SCHEMA_VERSION = "{ENGINE_SCHEMA_VERSION}" as const;
{_array("COMMAND_TYPES", COMMAND_TYPES)}
{_array("COMMAND_STATUSES", COMMAND_STATUSES)}
{_array("RUNTIME_STATES", RUNTIME_STATES)}

export type CommandType = typeof COMMAND_TYPES[number];
export type CommandStatus = typeof COMMAND_STATUSES[number];
export type RuntimeState = typeof RUNTIME_STATES[number];

export interface CommandReceipt {{
  schema_version: typeof ENGINE_SCHEMA_VERSION;
  command_id: string;
  command_type: CommandType;
  project_id: string;
  engine_session_id: string;
  stage_epoch: string;
  status: CommandStatus;
  message: string;
  error_code: string | null;
  applied_revision: string | null;
  build_fingerprint: string | null;
}}

export interface SimulationSnapshot {{
  schema_version: typeof ENGINE_SCHEMA_VERSION;
  engine_session_id: string;
  stage_epoch: string;
  project_id: string;
  applied_revision: string | null;
  run_id: string | null;
  sequence: number;
  runtime_state: RuntimeState;
  safety_state: string | null;
  safety_reason: string | null;
  permitted_commands: CommandType[];
  capabilities: string[];
  sim_time_s: number | null;
  sampled_at_utc: string | null;
  frame_id: string;
  position_m: [number, number, number] | null;
  yaw_rad: number | null;
  roll_rad: number | null;
  pitch_rad: number | null;
  linear_speed_mps: number | null;
  distance_to_goal_m: number | null;
  cross_track_error_m: number | null;
  telemetry_available: boolean;
}}

export interface Operation {{
  command_id: string;
  command_type: CommandType;
  project_id: string;
  engine_session_id: string;
  stage_epoch: string;
  expected_applied_revision: string | null;
  status: CommandStatus;
  receipt: CommandReceipt | null;
}}
'''


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != expected:
            print(f"generated contract is stale: {TARGET}", file=sys.stderr)
            return 1
        print(f"generated contract is current: schema={ENGINE_SCHEMA_VERSION}")
        return 0
    TARGET.write_text(expected, encoding="utf-8")
    print(f"generated {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
