import { chromium, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
const base = process.env.TWINPULSE_REHEARSAL_URL, bootstrap = process.env.TWINPULSE_REHEARSAL_BOOTSTRAP;
const output = process.env.TWINPULSE_REHEARSAL_OUTPUT, chrome = process.env.TWINPULSE_REHEARSAL_CHROME;
if (!base || new URL(base).hostname !== '127.0.0.1' || !bootstrap || !output || !chrome) throw new Error('Owned local configuration required');
const result = { status: 'FAIL', external_requests: 0, builds: 0, replays:0, page_errors: 0, checks: [] };
let browser, step = 'bootstrap';
try {
  browser = await chromium.launch({ executablePath: chrome, headless: true });
  const context = await browser.newContext({ viewport: { width: 1366, height: 950 }, acceptDownloads:true });
  await context.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.origin !== base && !['blob:', 'data:'].includes(url.protocol)) { result.external_requests++; return route.abort(); }
    if (url.pathname === '/v1/product/bedroom/build') result.builds++;
    if (url.pathname === '/v1/product/bedroom/replay') result.replays++;
    if (url.pathname.startsWith('/v1/product/robot/')) return route.abort();
    if (url.pathname === '/v1/product/commands') return route.abort();
    return route.continue();
  });
  const page = await context.newPage(); page.on('pageerror', () => result.page_errors++);
  await page.goto(`${base}/#bootstrap=${encodeURIComponent(bootstrap)}`);
  await expect(page.getByText('Backend ready', { exact: true })).toBeVisible({ timeout: 20000 });
  expect(new URL(page.url()).hash).toBe('');
  const state = () => page.evaluate(async () => (await fetch('/v1/product/state')).json());
  await expect.poll(async () => (await state()).engine_connected, { timeout: 30000 }).toBe(true);
  const panel = page.getByRole('region', { name: 'Photo-based room Digital Twin' });
  step = 'prepare';
  await panel.getByText('Load saved room and model').click();
  const build = panel.getByText('Display room + Burger in Isaac');
  await expect(build).toBeDisabled();
  expect((await state()).operations).toHaveLength(0);
  result.checks.push('prepare_no_engine_command');
  step='goal_evidence';
  const evidenceResponse=page.waitForResponse(r=>r.url().endsWith('/bedroom/geometry-evidence'));
  await panel.getByText('Inspect sensor pose and robot footprint evidence').click();
  const evidence=await (await evidenceResponse).json();
  expect(evidence.base_link_to_scan_xyz_m).toEqual([-.032,0,.172]);expect(evidence.saved_scan.frames).toBe(74);
  fs.writeFileSync(path.join(output,'geometry-evidence.json'),JSON.stringify(evidence,null,2));
  await panel.getByLabel('Twin goal X',{exact:true}).fill('0.2');
  await panel.getByLabel('Twin goal Y',{exact:true}).fill('0.3');
  await panel.getByText('Review goal coordinate mapping · no movement').click();
  await expect(panel.getByText(/no measured correspondence evidence/)).toBeVisible();
  expect((await state()).operations).toHaveLength(0);
  // Explicit artificial correspondences; this is not evidence for the user's room.
  const refField=panel.getByLabel('Twin odom correspondence evidence JSON');
  await panel.getByText('Enter explicit correspondence evidence · leave blank if unavailable').click();
  const contextText=await panel.getByLabel('Room goal and robot coordinate review').innerText();
  const scene=contextText.match(/scene_revision: ([a-f0-9]{64})/)[1];
  const reference={schema:'twin-odom-reference-1.0',scene_revision:scene,evidence_revision:evidence.revision,
    boot_id:'synthetic-test-only',basis:'synthetic_test_fixture',pairs:[[0,0],[1,0],[0,1]].map(p=>({twin_xy_m:p,odom_xy_m:[1-p[1],2+p[0]]}))};
  await refField.fill(JSON.stringify(reference));
  const goalResponse=page.waitForResponse(r=>r.url().endsWith('/bedroom/goal-preview'));
  await panel.getByText('Review goal coordinate mapping · no movement').click();
  const goal=await(await goalResponse).json();
  expect(goal.odom_goal_candidate_m[0]).toBeCloseTo(.7);expect(goal.odom_goal_candidate_m[1]).toBeCloseTo(2.2);
  expect(goal.motion_authorized).toBe(false);expect(goal.mission_request).toBe(null);
  fs.writeFileSync(path.join(output,'synthetic-goal-preview.json'),JSON.stringify(goal,null,2));
  await expect(panel.getByText(/Odom candidate:/)).toBeVisible();
  await panel.getByLabel('Room goal and robot coordinate review').screenshot({path:path.join(output,'goal-evidence-desktop.png')});
  await refField.fill('');
  expect((await state()).operations).toHaveLength(0);
  result.checks.push('pinned_model_saved_scan_and_missing_tf_no_goal_invention','synthetic_reference_goal_transform_no_mission_or_build');
  step = 'build';
  await panel.getByRole('checkbox').check();
  await expect(build).toBeEnabled(); await build.click();
  await expect(panel.getByText(/Room \+ Burger displayed/)).toBeVisible({ timeout: 60000 });
  const product = await state();
  expect(product.operations).toHaveLength(1);
  expect(product.operations[0].command_type).toBe('build_site_scene');
  expect(product.operations[0].status).toBe('succeeded');
  expect(product.snapshot.permitted_commands).not.toContain('run');
  result.checks.push('explicit_UI_API_broker_bridge_Isaac_receipt_and_snapshot', 'no_run_authority');
  step='synthetic_suite';
  const response=page.waitForResponse(r=>r.url().endsWith('/bedroom/offline-acceptance'));
  await panel.getByText('Run complete PC synthetic suite').click();
  const suite=await (await response).json();
  expect(suite.status).toBe('SYNTHETIC_PASS');
  expect(suite.motion_authorized).toBe(false);expect(suite.robot_connection).toBe(false);
  expect(suite.records.detour.status).toBe('ARRIVED');
  expect(suite.records.detour_no_path.status).toBe('NO_PATH');
  expect(suite.records.stale_scan.status).toBe('SCAN_STALE');
  await expect(panel.getByLabel('PC synthetic suite result')).toBeVisible();
  await panel.getByText('Review detour no path record').click();
  await expect(panel.getByText('NO_PATH · not physical validation')).toBeVisible();
  result.checks.push('single_UI_action_synthetic_route_detour_no_path_stale_and_comparison');
  fs.writeFileSync(path.join(output,'synthetic-suite.json'),JSON.stringify(suite,null,2));
  const downloadEvent=page.waitForEvent('download');
  await panel.getByText('Save all synthetic records and comparison').click();
  const savedBundle=path.join(output,'server-exported-synthetic-suite.json');
  await (await downloadEvent).saveAs(savedBundle);
  step='saved_suite_reopen';
  await page.reload();
  await expect(page.getByText('Backend ready',{exact:true})).toBeVisible({timeout:20000});
  await panel.getByText('Load saved room and model').click();
  const imported=page.waitForResponse(r=>r.url().endsWith('/bedroom/offline-acceptance-import'));
  await panel.getByLabel(/Reopen saved PC synthetic suite/).setInputFiles(savedBundle);
  const reopenedResponse=await(await imported).json();
  if(reopenedResponse.revision!==suite.revision)throw new Error(`Saved suite import: ${reopenedResponse.error?.code??'missing_revision'} · ${reopenedResponse.error?.message??'no message'}`);
  await expect(panel.getByLabel('PC synthetic suite result')).toBeVisible();
  await panel.getByText('Review detour no path record').click();
  await expect(panel.getByText('NO_PATH · not physical validation')).toBeVisible();
  await panel.getByRole('checkbox').check();
  result.checks.push('saved_synthetic_bundle_reopened_after_page_reload_without_new_motion');
  step='synthetic_replay';
  const comparison=suite.comparison;
  expect(comparison.eligible_for_efficiency_comparison).toBe(true);
  fs.writeFileSync(path.join(output,'comparison.json'),JSON.stringify(comparison,null,2));
  const mission=comparison.candidates[1].record;
  expect(mission.scenario).toBe('direct');
  await panel.getByText('B review record',{exact:true}).click();
  fs.writeFileSync(path.join(output,'mission.json'),JSON.stringify(mission,null,2));
  await expect(panel.getByText('ARRIVED · not physical validation')).toBeVisible();
  const slider=panel.getByRole('slider',{name:'Synthetic record frame'});
  for(const frame of [0,Math.floor(mission.events.length/2),mission.events.length]){
    await slider.fill(String(frame));expect(result.replays).toBe(frame===0?0:frame===mission.events.length?2:1);
    await panel.getByText('Display selected record in Isaac').click();
    await expect(panel.getByText(new RegExp(`Synthetic frame ${frame} displayed`))).toBeVisible({timeout:60000});
  }
  expect(result.replays).toBe(3);
  expect((await state()).snapshot.permitted_commands).not.toContain('run');
  result.checks.push('explicit_source_bound_start_mid_final_3D_seek_no_timeline_run');
  result.checks.push('same_condition_comparison_B_record_to_actual_Isaac');
  await panel.screenshot({ path: path.join(output, 'bedroom-desktop.png') });
  step = 'transport_failure';
  await context.route('**/v1/product/state', route => route.abort('connectionfailed'));
  await expect(build).toBeDisabled({ timeout: 7000 });
  await expect(panel.getByText(/Past display success/)).toBeVisible();
  result.checks.push('disconnected_state_does_not_claim_current_display');
  await context.unroute('**/v1/product/state');
  await expect(build).toBeEnabled({ timeout: 10000 });
  expect(result.builds).toBe(1);
  await page.setViewportSize({ width: 390, height: 844 });
  await panel.screenshot({ path: path.join(output, 'bedroom-mobile.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  expect(result.page_errors).toBe(0); expect(result.external_requests).toBe(0);
  result.checks.push('recovery_no_automatic_build', 'mobile_no_overflow');
  result.status = 'PASS';
} catch (error) {
  result.step = step;
  result.error = String(error.message).split(bootstrap).join('[redacted]').split(base).join('[local]').split('\n').slice(0,8).join('\n');
} finally {
  if (browser) await browser.close();
  fs.writeFileSync(path.join(output, 'browser-result.json'), JSON.stringify(result, null, 2));
}
process.exitCode = result.status === 'PASS' ? 0 : 1;
